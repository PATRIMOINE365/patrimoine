/**
 * Messages carrying a value — "…balance of {balance}" — cannot be looked
 * up once the value is filled in, so they are matched by pattern. Most
 * specific first: a broad template would otherwise swallow a narrower one.
 *
 * @type {ReadonlyArray<readonly [RegExp, string]>}
 */
export const ERROR_CODE_PATTERNS = [
    [/^le retrait ne peut pas dépasser le solde disponible du compte de retrait de .+?\.$/u, 'PM-4056'],
    [/^withdrawal cannot exceed the available payout account balance of .+?\.$/u, 'PM-4056'],
];

/**
 * The code for a message the browser is about to show, or null when the
 * sentence belongs to no catalogued error.
 *
 * @param {string} message
 * @returns {string|null}
 */
export function errorCodeForMessage(message) {
    if (typeof message !== 'string' || message === '') {
        return null;
    }

    const text = message
        .toLowerCase()
        .replace(/\s+/g, ' ')
        .trim();

    const exact = ERROR_CODES_BY_MESSAGE[text];

    if (exact !== undefined) {
        return exact;
    }

    for (const [pattern, code] of ERROR_CODE_PATTERNS) {
        if (pattern.test(text)) {
            return code;
        }
    }

    return null;
}
