/**
 * Resolve a translation from the requested language with English fallback.
 *
 * @param {string} language
 * @param {string} key
 * @returns {string}
 */
export function translationFor(
    language,
    key
) {
    const english =
        translations.en
        || {};

    const catalogue =
        translations[language]
        || english;

    return catalogue[key]
        ?? english[key]
        ?? key;
}
