/*
|--------------------------------------------------------------------------
| Keeping `hidden` hidden
|--------------------------------------------------------------------------
|
| Tailwind's utilities live in a cascade layer. Patrimoine's own component
| classes do not, and an unlayered rule beats a layered one whatever the
| specificity says — so a component that sets `display` wins against the
| `hidden` utility and the element stays on screen. That is not a theory:
| it left the lease wizard showing its create-a-new-property fields while
| an existing property was selected, and its draft and submit buttons
| showing on every step.
|
| The blunt fix — `.hidden { display: none !important }` — cannot be used,
| because `hidden xl:block` is a real and correct pattern here (the top bar
| date) and the utility that reveals it is layered too.
|
| So each offending component gets a companion rule of its own. Two class
| selectors beat one, and nothing layered is touched.
|
| Run with:  node scripts/generate-hidden-guards.mjs
|
| HiddenUtilityTest fails if a component starts setting `display` and is
| not listed here, so this cannot silently fall behind again.
|
*/

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = join(root, 'resources/css/app.css');
const outPath = join(root, 'resources/css/hidden-guards.css');

/**
 * Component classes that set a display other than none.
 *
 * @param {string} css
 * @returns {string[]}
 */
export function offendingClasses(css) {
    /*
     * Comments go first. A rule preceded by one would otherwise lose its
     * opening selector to the comment text, which is how .pm-button-primary
     * escaped the first version of this list.
     */
    const source = css
        .replace(/@import\s+'\.\/hidden-guards\.css';\n?/, '')
        .replace(/\/\*[\s\S]*?\*\//g, '');

    const found = new Set();

    /* selector { … } — good enough for a stylesheet we write ourselves. */
    for (const [, selector, body] of source.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
        const display = body.match(/(?:^|[;\s])display\s*:\s*([a-z-]+)/);

        if (! display || display[1] === 'none') {
            continue;
        }

        for (const part of selector.split(',')) {
            const trimmed = part.trim();

            /*
             * Only plain single-class component selectors can be defeated
             * this way — anything more specific already outranks a bare
             * utility, and a selector carrying `hidden` is a guard.
             */
            const match = trimmed.match(/^\.((?:pm|shell|theme|rbac)[a-z0-9-]*)$/);

            if (match && ! trimmed.includes('hidden')) {
                found.add(match[1]);
            }
        }
    }

    return [...found].sort();
}

const classes = offendingClasses(
    readFileSync(cssPath, 'utf8')
);

writeFileSync(
    outPath,
    `/*
|--------------------------------------------------------------------------
| Keeping \`hidden\` hidden
|--------------------------------------------------------------------------
|
| Generated by scripts/generate-hidden-guards.mjs. Do not edit by hand.
|
| Tailwind's \`hidden\` utility is layered and these component classes are
| not, so without a rule of their own they would win and an element told to
| be hidden would stay on screen. Two class selectors beat one.
|
| ${classes.length} components.
|
*/

${classes.map((name) => `.${name}.hidden`).join(',\n')} {
    display: none;
}
`,
);

console.log(`guarded ${classes.length} components:`, classes.join(', '));
